func TestShouldSkipGeneratedFileBranches(t *testing.T) {
	dir := t.TempDir()
	realFile := filepath.Join(dir, "real.go")
	if err := os.WriteFile(realFile, []byte("package p\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	missing := filepath.Join(dir, "missing.go")
	bad := filepath.Join(dir, "bad.go")
	gen := filepath.Join(dir, "gen.go")
	// Package GoFiles include missing/bad/gen so the read/parse error branches run.
	pkg := &packages.Package{GoFiles: []string{realFile, missing, bad, gen}}
	if !shouldSkipGeneratedFile(pkg, "") {
		t.Fatal("empty file should be skipped")
	}
	if shouldSkipGeneratedFile(pkg, filepath.Clean(realFile)) {
		t.Fatal("normal file should not be skipped")
	}
	if !shouldSkipGeneratedFile(pkg, filepath.Join(dir, "other.go")) {
		t.Fatal("non-package file should be skipped")
	}
	if !shouldSkipGeneratedFile(pkg, missing) {
		t.Fatal("missing (unreadable) file should be skipped")
	}
	if err := os.WriteFile(bad, []byte("this is {{{ not go at all &&&"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !shouldSkipGeneratedFile(pkg, bad) {
		t.Fatal("invalid source should be skipped")
	}
	if err := os.WriteFile(gen, []byte("// Code generated by x. DO NOT EDIT.\n\npackage p\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !shouldSkipGeneratedFile(pkg, gen) {
		t.Fatal("generated file should be skipped")
	}
}

